namespace bre::internal::codegen {
    struct Symbol
    {
        bool isConst;
        double varCount;
    };
    using compiler_symbol_table = std::unordered_map<std::string, Symbol>;

    class WaveCoder {
    private:
        int v_count = 0;                                                            // Variable counts (initialize 0).
        int cp_count = 0;                                                           // Constant Pool counts (initialize 0).
        compiler_symbol_table symbol_table;                                         // Map to translate variable names to number of vm variable position.
        LabelTable label_table;                                                     // Map for Labels
        std::vector<std::unique_ptr<Node>> ast;                                     // AST generated by parser.
        brevm::bytecodePool output;                                                 // Breeze Bytecode generated by Compiler (this).
        brevm::constantPool constant_pool;                                          // Constant pool generated by Codegen (this).

        void push(brevm::OPC opcode);
        void push_const(std::shared_ptr<brevm::RuntimeValue> v);
        void store(std::string& identifier, bool isconst);
        void compile_exp(Node& n);
        void compile_binexp(Node& node);
        void compile_node(Node& n);
        void isdef(std::string& identifier);
    public:
        WaveCoder(std::vector<std::unique_ptr<Node>> nodes);
        virtual ~WaveCoder() = default;
        void compile();
        std::vector<std::unique_ptr<Node>>& getAST() { return ast; };
        brevm::bytecodePool& getOutput() { return output; };
        brevm::constantPool getCP() { return constant_pool; };
        void eject_symbol(const std::string& symbol, const brevm::RuntimeValue& value, bool isConst);
    };
} // namespace wave::internal

